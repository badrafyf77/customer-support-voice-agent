CREATE TABLE public.exam_attempts (
  id uuid NOT NULL DEFAULT gen_random_uuid(),
  exam_id uuid NOT NULL,
  student_user_id uuid NOT NULL,
  enrollment_id uuid,
  attempt_number integer NOT NULL DEFAULT 1 CHECK (attempt_number > 0),
  status text NOT NULL DEFAULT 'in_progress'::text CHECK (status = ANY (ARRAY['in_progress'::text, 'submitted'::text, 'evaluated'::text, 'cancelled'::text, 'expired'::text])),
  started_at timestamp with time zone DEFAULT now(),
  ended_at timestamp with time zone,
  submitted_at timestamp with time zone,
  duration_seconds integer CHECK (duration_seconds IS NULL OR duration_seconds >= 0),
  conversation_history jsonb NOT NULL DEFAULT '[]'::jsonb,
  written_answers jsonb NOT NULL DEFAULT '[]'::jsonb,
  overall_score numeric CHECK (overall_score IS NULL OR overall_score >= 0::numeric AND overall_score <= 100::numeric),
  criterion_scores jsonb NOT NULL DEFAULT '{}'::jsonb,
  feedback text,
  evaluator_summary jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamp with time zone DEFAULT now(),
  updated_at timestamp with time zone DEFAULT now(),
  CONSTRAINT exam_attempts_pkey PRIMARY KEY (id),
  CONSTRAINT exam_attempts_exam_id_fkey FOREIGN KEY (exam_id) REFERENCES public.exams(id),
  CONSTRAINT exam_attempts_student_user_id_fkey FOREIGN KEY (student_user_id) REFERENCES auth.users(id),
  CONSTRAINT exam_attempts_enrollment_id_fkey FOREIGN KEY (enrollment_id) REFERENCES public.exam_enrollments(id)
);
