const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const ts=require('typescript');
const source=fs.readFileSync(require.resolve('../src/lib/generation.ts'),'utf8');
const compiled=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText;
const sandbox={exports:{}};vm.runInNewContext(compiled,sandbox);
const {PlaybackGeneration}=sandbox.exports;
const guard=new PlaybackGeneration();
assert.equal(guard.accept(undefined),true,'Unscoped English remains supported');
assert.equal(guard.accept(1),true);
assert.equal(guard.stop(1),true);
assert.equal(guard.accept(1),false,'Late audio and partials stay canceled');
assert.equal(guard.accept(2),true,'The next turn can play immediately');
assert.equal(guard.stop(1),false,'Old Stop must not clear newer audio');
assert.equal(guard.accept(2),true);
assert.equal(guard.accept(0),false);
assert.equal(guard.accept(undefined),false,'Scoped Darija cannot accept unscoped late frames');
assert.equal(guard.stop(),true);
assert.equal(guard.accept(2),false);
assert.equal(guard.accept(3),true);
assert.equal(new PlaybackGeneration().accept(1),true,'A new socket starts a new lease');
console.log('Generation ordering, scoped cancellation, legacy compatibility and reconnect checks passed');
